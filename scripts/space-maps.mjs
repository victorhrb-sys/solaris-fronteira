// Offline calibration; retain the original bank and persist only uniform scales.
import {approvedMaps} from '../public/approved-maps.mjs';
import {writeFileSync} from 'node:fs';
export function inspect(m,scale){
 const n=m.points.length,dist=m.points.map(([x,y])=>m.points.map(([a,b])=>Math.hypot(x-a,y-b)*scale));
 const adj=dist.map((row,i)=>row.flatMap((v,j)=>i!==j&&v<=340?[j]:[]));
 for(let blocked=0;blocked<n;blocked++){
  const seen=new Set([blocked===0?1:0]),todo=[...seen];
  while(todo.length)for(const j of adj[todo.pop()])if(j!==blocked&&!seen.has(j)){seen.add(j);todo.push(j);}
  if(seen.size!==n-1)return null;
 }
 const d=dist.map((r,i)=>r.map((v,j)=>i===j?0:v<=340?Math.ceil(v/190):999));
 for(let k=0;k<n;k++)for(let i=0;i<n;i++)for(let j=0;j<n;j++)d[i][j]=Math.min(d[i][j],d[i][k]+d[k][j]);
 const span=a=>Math.max(...a)-Math.min(...a);
 const access=[1,2,3,4].map(t=>m.homes.map(h=>d[h].filter(v=>v>0&&v<=t).length));
 const near=m.homes.map(h=>Math.min(...m.homes.filter(j=>j!==h).map(j=>d[h][j])));
 const territory=Array(m.players).fill(0);
 for(let j=0;j<n;j++){const ranked=m.homes.map((h,i)=>[d[h][j],i]).sort((a,b)=>a[0]-b[0]);if(ranked[0][0]<ranked[1][0])territory[ranked[0][1]]++;}
 if(access[0].some(v=>v<1)||span(access[0])>1||access[1].some(v=>v<3)||span(access[1])>3||span(access[2])>5||span(access[3])>7||near.some(v=>v<4||v>8)||span(near)>2||span(territory)>6)return null;
 return {isolated:dist.filter((r,i)=>r.every((v,j)=>i===j||v>190)).length};
}
if(process.argv[1]?.endsWith('space-maps.mjs')){
 const scales={},stats=[];
 for(const m of approvedMaps){
  let scale=1,metrics=inspect(m,1);
  for(let step=35;step>=1;step--){const candidate=1+step/100,result=inspect(m,candidate);if(result){scale=candidate;metrics=result;break;}}
  scales[m.id]=scale;stats.push({scale,...metrics});
 }
 writeFileSync(new URL('../public/map-spacing.mjs',import.meta.url),'// Generated by scripts/space-maps.mjs; original geometries remain intact.\nexport const mapScales='+JSON.stringify(scales)+';\nexport function spacedMap(map){const scale=mapScales[map.id];if(!scale)throw Error("Missing map spacing");return {...map,version:`${map.version}-spaced-v1`,points:map.points.map(([x,y])=>[x*scale,y*scale])};}\n','utf8');
 console.log(JSON.stringify({maps:stats.length,minScale:Math.min(...stats.map(s=>s.scale)),meanScale:stats.reduce((a,s)=>a+s.scale,0)/stats.length,mapsWithIsolated:stats.filter(s=>s.isolated>0).length,isolated:stats.reduce((a,s)=>a+s.isolated,0)}));
}
